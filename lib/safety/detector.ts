/**
 * Сигналы безопасности в сообщениях пользователя. Работает на устройстве, без нейросети и
 * ДО любого запроса к серверу: при сигнале тренер отвечает заготовленным, проверенным текстом.
 * Намеренно перестраховывается: лучше лишний раз спросить «как ты?», чем пропустить беду.
 */

export type SafetyKind = "crisis" | "eating" | "pain";

/** Русские слова без `\b` (в JS он не работает с кириллицей): край слова — не буква. */
function word(pattern: string): string {
  return `(?<![а-яёa-z])(?:${pattern})`;
}

