/**
 * Что имел в виду пользователь — грубо, по ключевым словам. Нужно, когда нейросети нет
 * (нет ключа, закончился лимит, пропал интернет) и во время звонка. Порядок правил важен:
 * сначала то, на что тренер реагирует жёстче всего.
 */
export function classifyIntent(text: string): ScriptedCategory {
  const clean = text.toLowerCase().replace(/\s+/g, " ").trim();
  if (!clean) return "fallback";
  for (const rule of RULES) {
    if (rule.re.test(clean)) return rule.category;
  }
  return "fallback";
}
