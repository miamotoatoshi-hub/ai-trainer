import { describe, expect, it } from "vitest";
import { plural } from "@/lib/plural";

const forms = ["тренировка", "тренировки", "тренировок"] as const;

describe("plural()", () => {
  it.each([
    [0, "тренировок"],
    [1, "тренировка"],
    [2, "тренировки"],
    [4, "тренировки"],
    [5, "тренировок"],
    [11, "тренировок"],
    [12, "тренировок"],
    [14, "тренировок"],
    [21, "тренировка"],
    [22, "тренировки"],
    [25, "тренировок"],
    [101, "тренировка"],
    [111, "тренировок"],
  ])("%i → %s", (n, expected) => {
    expect(plural(n, forms)).toBe(expected);
  });
});
