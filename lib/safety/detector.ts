const CRISIS_RE = new RegExp(CRISIS, "i");
const EATING_RE = new RegExp(EATING, "i");
const PAIN_RE = new RegExp(PAIN, "i");
const MEDICAL_RE = new RegExp(MEDICAL, "i");

/** Нормализация: нижний регистр, «ё»→«е» не делаем (шаблоны покрывают оба написания), лишние пробелы. */
function normalize(text: string): string {
  return text.toLowerCase().replace(/\s+/g, " ").trim();
}

/** Самый серьёзный сигнал в сообщении или null. Порядок: кризис → еда → боль → лекарства. */
export function detectSafety(text: string): SafetyKind | null {
  const clean = normalize(text);
  if (!clean) return null;
  if (CRISIS_RE.test(clean)) return "crisis";
  if (EATING_RE.test(clean)) return "eating";
  if (PAIN_RE.test(clean)) return "pain";
  if (MEDICAL_RE.test(clean)) return "medical";
  return null;
}
