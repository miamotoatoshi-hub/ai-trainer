import { describe, expect, it } from "vitest";
import { detectSafety } from "@/lib/safety/detector";

describe("detectSafety — кризис", () => {
  it.each([
    "я не хочу жить",
    "Хочу умереть",
    "думаю покончить с собой",
    "лучше бы меня не было",
    "я режу себя",
    "всем будет лучше без меня",
    "мне кажется, я никому не нужен",
    "хочу причинить себе вред",
  ])("%s", (text) => {
    expect(detectSafety(text)).toBe("crisis");
  });
});

describe("detectSafety — еда и тело", () => {
  it.each([
    "я сегодня не ем",
    "хочу похудеть на 10 кг за неделю",
    "я голодаю уже три дня",
    "вызываю рвоту после еды",
    "я ненавижу своё тело",
    "я слишком толстая",
    "у меня анорексия",
  ])("%s", (text) => {
    expect(detectSafety(text)).toBe("eating");
  });
});

describe("detectSafety — боль и самочувствие", () => {
  it.each([
    "у меня болит колено",
    "больно приседать",
    "кружится голова",
    "защемило спину",
    "меня тошнит после зарядки",
    "я потянул мышцу",
    "колет в боку",
    "темнеет в глазах",
    "задыхаюсь",
  ])("%s", (text) => {
    expect(detectSafety(text)).toBe("pain");
  });
});

describe("detectSafety — обычные сообщения не срабатывают", () => {
  it.each([
    "привет",
    "тяжело",
    "давай тренироваться",
    "я устал",
    "больше не могу ждать",
    "у меня сегодня контрольная",
    "жду тренировку",
    "сегодня не хочу тренироваться",
    "съел бутерброд и готов",
    "не ем сладкое",
  ])("%s", (text) => {
    // «не ем сладкое» — осознанная перестраховка: слово «не ем» подходит под шаблон про еду.
    const expected = text === "не ем сладкое" ? "eating" : null;
    expect(detectSafety(text)).toBe(expected);
  });

  it("кризис важнее остального в одном сообщении", () => {
    expect(detectSafety("у меня болит колено и я не хочу жить")).toBe("crisis");
    expect(detectSafety("болит живот, не ем второй день")).toBe("eating");
  });

  it("пустая строка и пробелы — ничего", () => {
    expect(detectSafety("")).toBeNull();
    expect(detectSafety("   ")).toBeNull();
  });
});
